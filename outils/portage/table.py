lignes = []
for l in open(os.path.join(ICI, 'correspondances.tsv')):
    a, s, meth, sc, ou = l.rstrip('\n').split('\t')
    a = int(a, 16)
    if a in FEUILLES: s, meth = FEUILLES[a], 'feuille (motif d\'octets)'
    elif a in DONNEES: s, meth = DONNEES[a], 'global (references exactes)'
    else:
        assert s != '-', hex(a); s = int(s, 16)
        meth = '%s %.2f' % (meth, float(sc))
    lignes.append((a, s, meth, ou.split(' ')[0]))
lignes.sort()
with open(os.path.join(ICI, 'table_steam.inc'), 'w') as f:
    for a, s, meth, ou in lignes:
        f.write('    { 0x%07X, 0x%07X },   // %s -- %s\n' % (a, s, ou, meth))
print(len(lignes), 'entrees')

